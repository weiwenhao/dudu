import { readFile, readdir, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));

/** Both phones use the Desktop's file marks and the same checked-in filename rules. */
export async function syncNativeFileIcons() {
  const rules = JSON.parse(await readFile(path.join(root, 'native/shared/file-type-icons.json'), 'utf8'));
  const assets = path.join(root, 'native/ios/Dudu/Assets.xcassets');
  const types = (await readdir(assets)).flatMap((name) => /^FileType-(.+)\.imageset$/.exec(name)?.[1] ?? []);
  const resource = (type) => `file_type_${type.replaceAll('-', '_')}`;
  for (const type of types) {
    execFileSync('rsvg-convert', ['-w', '96', '-h', '96', '-o',
      path.join(root, `native/android/app/src/main/res/drawable-nodpi/${resource(type)}.png`),
      path.join(assets, `FileType-${type}.imageset/FileType-${type}.svg`)]);
  }
  const pairs = (values, quote) => Object.entries(values).map(([key, value]) => `${quote(key)} to ${quote(value)}`);
  const q = JSON.stringify;
  await writeFile(path.join(root, 'native/android/app/src/main/java/app/dudu/android/ui/FileTypeIcons.kt'),
    '// Generated by scripts/sync-native-file-icons.mjs; marks and filename rules come from DSH.\n'
    + 'package app.dudu.android.ui\n\nimport androidx.compose.foundation.Image\nimport androidx.compose.foundation.layout.size\n'
    + 'import androidx.compose.runtime.Composable\nimport androidx.compose.ui.Modifier\nimport androidx.compose.ui.res.painterResource\n'
    + 'import androidx.compose.ui.unit.dp\nimport app.dudu.android.R\nimport java.util.Locale\n\n'
    + 'private val fileNames = mapOf(\n    ' + pairs(rules.names, q).join(',\n    ') + '\n)\n'
    + 'private val fileExtensions = mapOf(\n    ' + pairs(rules.extensions, q).join(',\n    ') + '\n)\n'
    + 'private val filePrefixes = listOf(' + rules.prefixes.map(([a, b]) => `${q(a)} to ${q(b)}`).join(', ') + ')\n'
    + 'private val fileSuffixes = listOf(' + rules.suffixes.map(([a, b]) => `${q(a)} to ${q(b)}`).join(', ') + ')\n'
    + 'private val fileMarks = mapOf(\n    ' + types.map((type) => `${q(type)} to R.drawable.${resource(type)}`).join(',\n    ') + '\n)\n\n'
    + '@Composable\ninternal fun FileTypeIcon(name: String?, size: Int = 24) {\n'
    + '    val filename = name.orEmpty().replace(\'\\\\\', \'/\').substringAfterLast(\'/\').lowercase(Locale.ROOT)\n'
    + '    val type = fileNames[filename] ?: filePrefixes.firstOrNull { filename.startsWith(it.first) }?.second\n'
    + '        ?: fileSuffixes.firstOrNull { filename.endsWith(it.first) }?.second ?: fileExtensions[filename.substringAfterLast(\'.\', "")]\n'
    + '    Image(painterResource(fileMarks[type] ?: R.drawable.changed_files), null, Modifier.size(size.dp))\n}\n');
  const dictionary = (values) => '[\n        ' + Object.entries(values).map(([key, value]) => `${q(key)}: ${q(value)}`).join(',\n        ') + '\n    ]';
  const tuples = (values) => '[' + values.map(([a, b]) => `(${q(a)}, ${q(b)})`).join(', ') + ']';
  await writeFile(path.join(root, 'native/ios/Dudu/Views/FileTypeIcon.swift'),
    '// Generated by scripts/sync-native-file-icons.mjs; marks and filename rules come from DSH.\nimport SwiftUI\n\n'
    + 'struct FileTypeIcon: View {\n    let name: String?\n    var size: CGFloat = 24\n\n'
    + '    private static let names: [String: String] = ' + dictionary(rules.names) + '\n'
    + '    private static let extensions: [String: String] = ' + dictionary(rules.extensions) + '\n'
    + '    private static let prefixes = ' + tuples(rules.prefixes) + '\n'
    + '    private static let suffixes = ' + tuples(rules.suffixes) + '\n'
    + '    private static let marks: Set<String> = [' + types.map(q).join(', ') + ']\n\n'
    + '    private var asset: String {\n'
    + '        let filename = (name ?? "").replacingOccurrences(of: "\\\\", with: "/").split(separator: "/").last.map(String.init)?.lowercased() ?? ""\n'
    + '        let ext = filename.lastIndex(of: ".").map { String(filename[filename.index(after: $0)...]) } ?? ""\n'
    + '        let type = Self.names[filename] ?? Self.prefixes.first(where: { filename.hasPrefix($0.0) })?.1\n'
    + '            ?? Self.suffixes.first(where: { filename.hasSuffix($0.0) })?.1 ?? Self.extensions[ext]\n'
    + '        return type.flatMap { Self.marks.contains($0) ? "FileType-\\($0)" : nil } ?? "ChangedFiles"\n    }\n\n'
    + '    var body: some View {\n        Image(asset).resizable().renderingMode(.original).scaledToFit()\n'
    + '            .frame(width: size, height: size).accessibilityHidden(true)\n    }\n}\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await syncNativeFileIcons();
}

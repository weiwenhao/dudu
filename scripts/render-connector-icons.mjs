// Renders the connector logos of the desktop interface (host/dudu-plugin/ui/connectors/icons/*.svg and *.png) as PNGs for the phone's asset catalog:
// native/ios/Dudu/Assets.xcassets/Connector-<key>.imageset, and the list of their keys the app reads (native/ios/Dudu/Views/ConnectorLogoKeys.swift).
// Run by hand when a logo is added or changed (scripts/collect-brand-logos.mjs collects them); the PNGs are committed, so the native build does not need a browser.
//   node scripts/render-connector-icons.mjs
import { Buffer } from 'node:buffer';
import { mkdir, readdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'host', 'dudu-plugin', 'ui', 'connectors', 'icons');
const target = join(root, 'native', 'ios', 'Dudu', 'Assets.xcassets');
const SIDE = 96; // pixels: the logo is drawn at 17 points, so this is sharp at 3x and then some
const MIME = { svg: 'image/svg+xml', png: 'image/png' };

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const keys = [];
try {
  const page = await browser.newPage({ viewport: { width: SIDE, height: SIDE }, deviceScaleFactor: 1 });
  for (const file of (await readdir(source)).filter((name) => /\.(svg|png)$/u.test(name)).sort()) {
    const [, key, extension] = /^(.+)\.(svg|png)$/u.exec(file);
    const url = `data:${MIME[extension]};base64,${Buffer.from(await readFile(join(source, file))).toString('base64')}`;
    await page.setContent(`<!doctype html><body style="margin:0;background:transparent"><img src="${url}" style="display:block;width:${SIDE}px;height:${SIDE}px;object-fit:contain"></body>`);
    await page.waitForFunction(() => document.images[0]?.complete);
    const folder = join(target, `Connector-${key}.imageset`);
    await mkdir(folder, { recursive: true });
    await page.screenshot({ path: join(folder, `Connector-${key}.png`), omitBackground: true });
    await writeFile(join(folder, 'Contents.json'), `${JSON.stringify({
      images: [{ filename: `Connector-${key}.png`, idiom: 'universal', scale: '3x' }],
      info: { author: 'xcode', version: 1 },
    }, null, 2)}\n`);
    keys.push(key);
    console.log(`Connector-${key}`);
  }
} finally {
  await browser.close();
}

// A logo that is no longer in the icons folder is no longer in the catalog either.
const present = new Set(keys);
for (const name of await readdir(target)) {
  const match = /^Connector-(.+)\.imageset$/u.exec(name);
  if (match && !present.has(match[1])) await rm(join(target, name), { recursive: true, force: true });
}

await writeFile(join(root, 'native', 'ios', 'Dudu', 'Views', 'ConnectorLogoKeys.swift'), `// Generated by scripts/render-connector-icons.mjs: the services that have a logo in the asset catalog (\`Connector-<key>\`). Do not edit.
enum ConnectorLogoKeys {
    static let all: Set<String> = [
${keys.map((key) => `        "${key}",`).join('\n')}
    ]
}
`);
await copyFile(join(source, 'NOTICE.md'), join(root, 'native', 'ios', 'Dudu', 'Resources', 'ConnectorLogoNotices.txt'));

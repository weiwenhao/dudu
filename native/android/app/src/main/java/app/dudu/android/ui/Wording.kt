@Composable
fun w(key: String): String {
    val chinese = LocalConfiguration.current.locales[0].language == "zh"
    return if (chinese) key else english[key] ?: key
}

@Composable
fun wp(key: String, count: Int): String {
    val chinese = LocalConfiguration.current.locales[0].language == "zh"
    val pattern = if (chinese) key else if (count == 1) englishSingular[key] ?: english[key] ?: key else english[key] ?: key
    return pattern.replace("%lld", count.toString())
}
